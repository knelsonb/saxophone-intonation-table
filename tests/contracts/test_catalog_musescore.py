"""Instrument catalog versus its source of truth, MuseScore's instruments.xml.

The catalog (intonation.catalog.instruments) stores a transposition and two baked
FINGERED ranges per instrument, generated by tools/musescore/sync_ranges.py. In the
XML ``transposeChromatic`` is ``sounding - written`` and ``aPitchRange`` /
``pPitchRange`` are SOUNDING ranges (MuseScore's "early amateur" and professional
tiers). For every key the catalog maps to a MuseScore id the contract is:

  * catalog transposition == transposeChromatic, or a KNOWN_TRANSPOSITION_DIVERGENCES
    entry;
  * keyed range == aPitchRange converted with the catalog transposition, or a
    recorded keyed exception (``sync_ranges.KEYED_EXCEPTIONS``) with a reason;
  * extended range == pPitchRange converted the same way and widened to contain
    the keyed range, or a recorded extension (``sync_ranges.EXTENDED_EXCEPTIONS``)
    with a reason;
  * keyed lies inside extended, and both sound inside the detector window.

The expected values are recomputed here from the parsed XML, so a change in the
generator's rules shows up as a failure, not as a silently regenerated table. A
recorded exception equal to the MuseScore value is stale and fails too.

Only the baked tables are read (``baked_keyed_range``, ``baked_extended_range``,
``_FAMILIES``); the user's ``~/.intonation_analyzer`` overrides and runtime customs
never enter.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

from intonation.catalog import instruments as si
from intonation.core.pitch import SAX_MIDI

_SYNC_PATH = (Path(__file__).resolve().parents[2]
              / 'tools' / 'musescore' / 'sync_ranges.py')
_spec = importlib.util.spec_from_file_location('musescore_sync_ranges', _SYNC_PATH)
sync_ranges = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sync_ranges)

MUSESCORE = sync_ranges.parse_instruments()
MUSESCORE_ID: dict[str, str] = sync_ranges.MUSESCORE_ID
KEYED_EXCEPTIONS = sync_ranges.KEYED_EXCEPTIONS
EXTENDED_EXCEPTIONS = sync_ranges.EXTENDED_EXCEPTIONS
HAND_SET = sync_ranges.HAND_SET

# Catalog transposition per key, from the baked family table (never from
# transp_map(), which also folds in runtime-registered customs).
CATALOG_TRANSP: dict[str, int] = {
    key: transp
    for (_fk, _de, _en, instruments) in si._FAMILIES
    for (key, transp, _d, _e) in instruments
}

# What the detector can read, sounding: A0..C8.
SOUNDING_WINDOW = (SAX_MIDI.start, SAX_MIDI.stop - 1)

# key -> ((catalog, musescore), reason). The sounding ranges agree with
# MuseScore for these, so only the written spelling of the instrument differs.
KNOWN_TRANSPOSITION_DIVERGENCES: dict[str, tuple[tuple[int, int], str]] = {
    'sousaphone_bbb': ((0, -14), 'catalog stores the sousaphone like the other tubas '
                                 '(written = sounding); MuseScore writes it 14 '
                                 'semitones up'),
    'rec_sopranino_f': ((12, 0), 'recorder convention: written an octave below '
                                 'sounding; MuseScore carries no transposition tag '
                                 'for recorders, so the parser reads 0'),
    'rec_soprano_c': ((12, 0), 'recorder convention: written an octave below '
                               'sounding; MuseScore carries no transposition tag '
                               'for recorders, so the parser reads 0'),
}


def _fingered(key: str, tier: str) -> tuple[int, int]:
    """MuseScore's ``tier`` ('a' or 'p') for ``key``, in catalog fingered MIDI."""
    ms = MUSESCORE[MUSESCORE_ID[key]]
    transp = CATALOG_TRANSP[key]
    return (ms[f'{tier}_lo'] - transp, ms[f'{tier}_hi'] - transp)


def _hull(a, b):
    return (min(a[0], b[0]), max(a[1], b[1]))


# ---------------------------------------------------------------------------
# Catalog versus MuseScore
# ---------------------------------------------------------------------------
@pytest.mark.parametrize('key', sorted(MUSESCORE_ID))
def test_transposition_matches_musescore_or_is_a_known_divergence(key: str) -> None:
    assert key in CATALOG_TRANSP, f'{key} is mapped to MuseScore but not in the catalog'
    pair = (CATALOG_TRANSP[key], MUSESCORE[MUSESCORE_ID[key]]['transp'])
    if key in KNOWN_TRANSPOSITION_DIVERGENCES:
        assert pair == KNOWN_TRANSPOSITION_DIVERGENCES[key][0]
    else:
        assert pair[0] == pair[1]


@pytest.mark.parametrize('key', sorted(MUSESCORE_ID))
def test_keyed_range_is_musescore_amateur_or_a_recorded_exception(key: str) -> None:
    baked = si.baked_keyed_range(key)
    amateur = _fingered(key, 'a')
    if key in KEYED_EXCEPTIONS:
        value, reason = KEYED_EXCEPTIONS[key]
        assert baked == value
        assert baked != amateur, f'{key}: stale keyed exception, MuseScore now agrees'
        assert reason.strip()
    else:
        assert baked == amateur


@pytest.mark.parametrize('key', sorted(MUSESCORE_ID))
def test_extended_range_is_musescore_professional_or_a_recorded_extension(key: str) -> None:
    baked = si.baked_extended_range(key)
    # The professional range, never narrower than the keyed range.
    default = _hull(_fingered(key, 'p'), si.baked_keyed_range(key))
    if key in EXTENDED_EXCEPTIONS:
        value, reason = EXTENDED_EXCEPTIONS[key]
        assert baked == value
        assert baked != default, f'{key}: stale extension, the default rule now agrees'
        assert reason.strip()
    else:
        assert baked == default


@pytest.mark.parametrize('key', sorted(HAND_SET))
def test_hand_set_keys_judge_nothing_out_of_range(key: str) -> None:
    """A hand-set key has no instrument behind it: its guide rows are the
    recorded range, and every note the detector reads counts as in range."""
    value, reason = HAND_SET[key]
    assert si.baked_keyed_range(key) == value
    lo, hi = si.baked_extended_range(key)
    transp = CATALOG_TRANSP[key]
    assert (lo + transp, hi + transp) == SOUNDING_WINDOW
    assert reason.strip()


def test_every_exception_names_a_mapped_catalog_key() -> None:
    for table in (KEYED_EXCEPTIONS, EXTENDED_EXCEPTIONS):
        for key, (value, reason) in table.items():
            assert key in CATALOG_TRANSP, f'{key}: exception for an unknown key'
            assert key in MUSESCORE_ID, f'{key}: exception for an unmapped key'
            assert isinstance(reason, str) and reason.strip(), f'{key}: no reason'
            assert len(value) == 2 and value[0] <= value[1], key
    for key, (_pair, reason) in KNOWN_TRANSPOSITION_DIVERGENCES.items():
        assert key in MUSESCORE_ID and reason.strip(), key


def test_every_catalog_key_is_mapped_or_hand_set() -> None:
    unaccounted = set(CATALOG_TRANSP) - set(MUSESCORE_ID) - set(HAND_SET)
    assert not unaccounted, f'catalog keys with no range decision: {sorted(unaccounted)}'
    assert set(HAND_SET) <= set(CATALOG_TRANSP)
    assert not set(HAND_SET) & set(MUSESCORE_ID)


def test_musescore_ids_resolve_and_are_unique() -> None:
    missing = [k for k, mid in MUSESCORE_ID.items() if mid not in MUSESCORE]
    assert not missing, f'ids absent from instruments.xml: {missing}'
    ids = list(MUSESCORE_ID.values())
    assert len(ids) == len(set(ids)), 'two catalog keys share one MuseScore id'


def test_oracle_parses_known_instruments() -> None:
    """Pins the parser against the XML so the comparison cannot pass vacuously."""
    assert len(MUSESCORE) > 100
    tenor = MUSESCORE['tenor-saxophone']
    assert tenor['transp'] == -14
    assert (tenor['a_lo'], tenor['a_hi']) == (44, 75)
    assert (tenor['p_lo'], tenor['p_hi']) == (44, 87)
    assert sync_ranges.to_fingered(sync_ranges.sounding_tier(tenor, 'a'), -14) == (58, 89)
    # The horn, not the singing voice, behind the bass-clef baritone.
    horn = MUSESCORE['baritone-horn']
    assert (horn['a_lo'], horn['a_hi'], horn['transp']) == (40, 67, 0)
    mellophone = MUSESCORE['mellophone']
    assert (mellophone['a_lo'], mellophone['a_hi'], mellophone['transp']) == (47, 74, -7)


def test_both_clefs_of_the_baritone_horn_sound_the_same_range() -> None:
    def sounding(key, rng):
        return (rng[0] + CATALOG_TRANSP[key], rng[1] + CATALOG_TRANSP[key])
    for tier in (si.baked_keyed_range, si.baked_extended_range):
        assert (sounding('baritone_bc', tier('baritone_bc'))
                == sounding('baritone_tc', tier('baritone_tc')))


# ---------------------------------------------------------------------------
# The generator is the source of the baked tables
# ---------------------------------------------------------------------------
def test_generator_reproduces_baked_tables() -> None:
    keyed, extended, _sources = sync_ranges.generate_ranges()
    assert list(keyed.items()) == list(si._KEYED_RANGES.items())
    assert list(extended.items()) == list(si._EXTENDED_RANGES.items())


def test_generator_output_is_the_text_in_the_catalog_module() -> None:
    """The printed tables are pasted verbatim, comments included."""
    source = Path(si.__file__).read_text(encoding='utf-8')
    for block in sync_ranges.render_tables():
        assert block in source, block.splitlines()[0]


