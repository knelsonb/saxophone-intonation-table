@pytest.mark.parametrize('key', sorted(CATALOG_TRANSP))
def test_keyed_range_lies_inside_extended(key: str) -> None:
    assert si.has_baked_range(key), f'{key} falls back to the generic range'
    k_lo, k_hi = si.baked_keyed_range(key)
    e_lo, e_hi = si.baked_extended_range(key)
    assert e_lo <= k_lo <= k_hi <= e_hi
    assert 12 <= k_hi - k_lo + 1 <= 88, 'table seeds at least an octave, at most the piano'


@pytest.mark.parametrize('key', sorted(CATALOG_TRANSP))
@pytest.mark.parametrize('tier', ['keyed', 'extended'])
def test_baked_sounding_range_is_inside_detector_window(key: str, tier: str) -> None:
    lo, hi = getattr(si, f'baked_{tier}_range')(key)
    transp = CATALOG_TRANSP[key]
    assert 0 <= lo <= hi <= 127
    assert SOUNDING_WINDOW[0] <= lo + transp, f'{key} sounds below A0'
    assert hi + transp <= SOUNDING_WINDOW[1], f'{key} sounds above C8'


def test_detector_window_is_a0_to_c8() -> None:
    assert SOUNDING_WINDOW == (21, 108)


def test_catalog_transposition_agrees_with_transp_map_without_customs(monkeypatch) -> None:
    monkeypatch.setattr(si, '_CUSTOMS', [])
    assert si.transp_map() == CATALOG_TRANSP


def test_baked_ranges_ignore_user_overrides(monkeypatch, tmp_path) -> None:
    """The contract tables read the baked ranges only; a user override must not
    leak into them, though keyed_range() follows it."""
    overrides = tmp_path / 'instrument_ranges.json'
    overrides.write_text('{"version": 1, "ranges": {"eb_alto": [1, 2]}}', encoding='utf-8')
    monkeypatch.setattr(si, '_active_overrides', si.RangeOverrides(overrides))
    assert si.keyed_range('eb_alto') == (1, 2)
    assert si.baked_keyed_range('eb_alto') == (58, 90)
    assert si.baked_extended_range('eb_alto') == (58, 101)
